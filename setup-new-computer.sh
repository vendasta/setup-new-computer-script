# SSH Key Setup for GitHub (SECOND - before Git operations)
printHeading "SSH Key Setup for GitHub"
printDivider
    if [ -f ~/.ssh/id_ed25519 ]; then
        echo "✔ SSH key already exists at ~/.ssh/id_ed25519"
        echo "✔ Your public key:"
        cat ~/.ssh/id_ed25519.pub
    else
        echo "Generating SSH key for GitHub..."
        read -p 'Enter your email address for SSH key: ' ssh_email
        
        # Generate SSH key
        ssh-keygen -t ed25519 -C "$ssh_email" -f ~/.ssh/id_ed25519 -N ""
        echo "✔ SSH key generated"
    fi
printDivider
    echo "✔ Starting SSH agent and adding key..."
    eval "$(ssh-agent -s)" > /dev/null 2>&1
    
    # Create SSH config if it doesn't exist
    if [ ! -f ~/.ssh/config ]; then
        echo "✔ Creating SSH config file..."
        mkdir -p ~/.ssh
        cat > ~/.ssh/config << EOF
Host github.com
  AddKeysToAgent yes
  UseKeychain yes
  IdentityFile ~/.ssh/id_ed25519
EOF
        echo "✔ SSH config created"
    else
        echo "✔ SSH config already exists - preserving existing configuration"
        # Check if GitHub host entry exists, if not add it safely
        if ! grep -q "Host github.com" ~/.ssh/config; then
            echo "✔ Adding GitHub SSH config to existing file..."
            cat >> ~/.ssh/config << EOF

# GitHub SSH configuration (added by setup script)
Host github.com
  AddKeysToAgent yes
  UseKeychain yes
  IdentityFile ~/.ssh/id_ed25519
EOF
            echo "✔ GitHub SSH config appended to existing SSH config"
        else
            echo "✔ GitHub SSH config already exists in SSH config"
        fi
    fi
printDivider
    echo "✔ Adding SSH key to SSH agent..."
    ssh-add --apple-use-keychain ~/.ssh/id_ed25519 > /dev/null 2>&1
printDivider
    echo "✔ Copying public key to clipboard..."
    pbcopy < ~/.ssh/id_ed25519.pub
    echo ""
